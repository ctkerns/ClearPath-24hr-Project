import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { createRouter, RouterProvider } from '@tanstack/react-router'
import { routeTree } from './routeTree.gen' // generated by the router Vite plugin
import { ApiError } from './lib/api'
import '@fontsource/ibm-plex-sans/400.css'
import '@fontsource/ibm-plex-sans/500.css'
import '@fontsource/ibm-plex-sans/600.css'
import '@fontsource/ibm-plex-mono/400.css'
import '@fontsource/ibm-plex-mono/500.css'
import './i18n'
import './index.css'

// One cache for all API data in the app.
// A 4xx answer (401, 403, 404, 422 ...) is the same on every try, so retry only network and server errors,
// and a page shows "not found" or "not for your role" at once instead of after three slow retries.
const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: (failures, error) =>
        error instanceof ApiError && error.status >= 400 && error.status < 500 && error.status !== 408 && error.status !== 429
          ? false
          : failures < 3,
    },
  },
})

const router = createRouter({ routeTree, context: { queryClient } })

// Registers the router type so links and params are type-checked everywhere
declare module '@tanstack/react-router' {
  interface Register {
    router: typeof router
  }
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <RouterProvider router={router} />
    </QueryClientProvider>
  </StrictMode>,
)
